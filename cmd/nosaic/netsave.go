const networkConfName = "network.conf"

// savedNetworkConfPath returns the switch's persistent network.conf path.
func savedNetworkConfPath() string {
	return filepath.Join(config.SiteDir, networkConfName)
}

// collectLinuxNet reads global IPv4/IPv6 addresses on switch interfaces and
// default routes from Linux so `config save` preserves management and L3
// addressing alongside the ASIC's L2/LAG/STP state.
func collectLinuxNet() (ifaces []string, routes []string) {
	ifs, err := net.Interfaces()
	if err == nil {
		sort.Slice(ifs, func(i, j int) bool { return ifs[i].Name < ifs[j].Name })
		for _, iface := range ifs {
			if iface.Flags&net.FlagLoopback != 0 {
				continue
			}
			if !isManagedIface(iface.Name) {
				continue
			}
			addrs, err := iface.Addrs()
			if err != nil {
				continue
			}
			for _, a := range addrs {
				ipNet, ok := a.(*net.IPNet)
				if !ok || ipNet.IP.IsLinkLocalUnicast() || ipNet.IP.IsLinkLocalMulticast() || ipNet.IP.IsLoopback() {
					continue
				}
				ones, _ := ipNet.Mask.Size()
				ifaces = append(ifaces, fmt.Sprintf("iface %s %s/%d", iface.Name, ipNet.IP.String(), ones))
			}
		}
	}

	if out, err := exec.Command("ip", "route", "show", "default").Output(); err == nil {
		for _, line := range strings.Split(string(out), "\n") {
			fields := strings.Fields(line)
			// default via <gw> dev <dev> ...
			var gw, dev string
			for i := 0; i+1 < len(fields); i++ {
				if fields[i] == "via" {
					gw = fields[i+1]
				} else if fields[i] == "dev" {
					dev = fields[i+1]
				}
			}
			if gw != "" && dev != "" {
				routes = append(routes, fmt.Sprintf("route default via %s dev %s", gw, dev))
			}
		}
	}
	return ifaces, routes
}

func isManagedIface(name string) bool {
	return name == "eth0" ||
		strings.HasPrefix(name, "swp") ||
		strings.HasPrefix(name, "et") ||
		strings.HasPrefix(name, "vlan") ||
		strings.HasPrefix(name, "po")
}

// renderRunningConfig renders the live switch state in network.conf format.
func renderRunningConfig(sw switchapi.Switch, ifaces, routes []string) (string, error) {
	var out []string
	out = append(out, "# Generated by nosaic config save.")

	if len(ifaces) > 0 {
		out = append(out, ifaces...)
	}
	if len(routes) > 0 {
		out = append(out, routes...)
	}

	// MAC aging (omit if default 300s or unsupported).
	if sec, err := sw.MACAging(); err == nil && sec != 300 {
		out = append(out, fmt.Sprintf("mac aging %d", sec))
	}

	// LAGs (and LACP system priority if non-default).
	lags, err := sw.LAGs()
	if err != nil && !errors.Is(err, switchapi.ErrUnsupported) {
		return "", fmt.Errorf("reading LAGs: %w", err)
	}
	sort.Slice(lags, func(i, j int) bool { return lags[i].Name < lags[j].Name })
	sysPrioEmitted := false
	for _, g := range lags {
		if !sysPrioEmitted && g.SystemPriority > 0 && g.SystemPriority != switchapi.LACPDefaultPriority {
			out = append(out, fmt.Sprintf("lacp system-priority %d", g.SystemPriority))
			sysPrioEmitted = true
		}
	}
	for _, g := range lags {
		mode := "static"
		if g.LACP {
			mode = "lacp"
		}
		var members []string
		for _, m := range g.Members {
			members = append(members, m.Port)
		}
		sort.Strings(members)
		line := fmt.Sprintf("lag %s %s %s", g.Name, mode, strings.Join(members, ","))
		if g.MLAG > 0 {
			line += fmt.Sprintf(" mlag %d", g.MLAG)
		}
		if g.LACP {
			if g.Options.Rate == "slow" {
				line += " rate slow"
			}
			if g.Options.Passive {
				line += " mode passive"
			}
			if g.Options.PortPriority > 0 && g.Options.PortPriority != switchapi.LACPDefaultPriority {
				line += fmt.Sprintf(" port-priority %d", g.Options.PortPriority)
			}
		}
		out = append(out, line)
	}

	// MLAG.
	if m, err := sw.MLAG(); err == nil && m.Enabled {
		line := fmt.Sprintf("mlag on peer-link %s", m.PeerLink)
		if m.PeerAddress != "" {
			line += " peer-address " + m.PeerAddress
		}
		if m.Priority > 0 && m.Priority != switchapi.MLAGDefaultPriority {
			line += fmt.Sprintf(" priority %d", m.Priority)
		}
		if m.HelloMs > 0 && m.HelloMs != 1000 {
			line += fmt.Sprintf(" hello %d", m.HelloMs)
		}
		if m.DeadMs > 0 && m.DeadMs != 3500 {
			line += fmt.Sprintf(" dead %d", m.DeadMs)
		}
		if m.SettleMs > 0 && m.SettleMs != 2500 {
			line += fmt.Sprintf(" settle %d", m.SettleMs)
		}
		if m.HeartbeatPort > 0 && m.HeartbeatPort != 47101 {
			line += fmt.Sprintf(" heartbeat-port %d", m.HeartbeatPort)
		}
		if m.ReloadDelay > 0 {
			line += fmt.Sprintf(" reload-delay %d", m.ReloadDelay)
		}
		out = append(out, line)
	}

	// STP.
	if st, err := sw.STP(); err == nil && st.Enabled {
		line := "stp on"
		if st.Priority != switchapi.STPDefaultPriority {
			line += fmt.Sprintf(" priority %d", st.Priority)
		}
		if st.HelloTime > 0 && st.HelloTime != 2 {
			line += fmt.Sprintf(" hello %d", st.HelloTime)
		}
		if st.ForwardDelay > 0 && st.ForwardDelay != 15 {
			line += fmt.Sprintf(" forward-delay %d", st.ForwardDelay)
		}
		if st.MaxAge > 0 && st.MaxAge != 20 {
			line += fmt.Sprintf(" max-age %d", st.MaxAge)
		}
		out = append(out, line)
		ports := append([]switchapi.STPPort(nil), st.Ports...)
		sort.Slice(ports, func(i, j int) bool { return ports[i].Port < ports[j].Port })
		for _, p := range ports {
			var opts []string
			if p.Edge {
				opts = append(opts, "edge")
			}
			if p.BPDUGuard {
				opts = append(opts, "bpdu-guard")
			}
			if p.RootGuard {
				opts = append(opts, "root-guard")
			}
			if p.Priority > 0 && p.Priority != 128 {
				opts = append(opts, fmt.Sprintf("priority %d", p.Priority))
			}
			if len(opts) > 0 {
				out = append(out, fmt.Sprintf("stp port %s %s", p.Port, strings.Join(opts, " ")))
			}
		}
	}

	// VLANs and per-port switchport membership.
	vlans, err := sw.VLANs()
	if err != nil && !errors.Is(err, switchapi.ErrUnsupported) {
		return "", fmt.Errorf("reading VLANs: %w", err)
	}
	sort.Slice(vlans, func(i, j int) bool { return vlans[i].VID < vlans[j].VID })

	type portMembership struct {
		tagged   []int
		untagged int
		tunnel   int
	}
	byPort := map[string]*portMembership{}
	for _, v := range vlans {
		out = append(out, fmt.Sprintf("vlan %d", v.VID))
		for _, m := range v.Members {
			pm := byPort[m.Port]
			if pm == nil {
				pm = &portMembership{}
				byPort[m.Port] = pm
			}
			if m.Tunnel {
				pm.tunnel = v.VID
			} else if m.Tagged {
				pm.tagged = append(pm.tagged, v.VID)
			} else {
				pm.untagged = v.VID
			}
		}
	}
	var portNames []string
	for p := range byPort {
		portNames = append(portNames, p)
	}
	sort.Strings(portNames)
	for _, p := range portNames {
		pm := byPort[p]
		if pm.tunnel > 0 {
			out = append(out, fmt.Sprintf("switchport %s tunnel %d", p, pm.tunnel))
			continue
		}
		if len(pm.tagged) == 0 && pm.untagged > 0 {
			out = append(out, fmt.Sprintf("switchport %s access %d", p, pm.untagged))
			continue
		}
		sort.Ints(pm.tagged)
		var vids []string
		for _, vid := range pm.tagged {
			vids = append(vids, strconv.Itoa(vid))
		}
		line := fmt.Sprintf("switchport %s trunk %s", p, strings.Join(vids, ","))
		if pm.untagged > 0 {
			line += fmt.Sprintf(" native %d", pm.untagged)
		}
		out = append(out, line)
	}

	// Virtual gateways (optional extension implemented by nosdclient.Client).
	if gwSw, ok := sw.(interface {
		Gateways() ([]switchapi.VirtualGateway, error)
	}); ok {
		if gws, err := gwSw.Gateways(); err == nil && len(gws) > 0 {
			sort.Slice(gws, func(i, j int) bool {
				if gws[i].SVI != gws[j].SVI {
					return gws[i].SVI < gws[j].SVI
				}
				return gws[i].Address.String() < gws[j].Address.String()
			})
			if gws[0].MAC != "" && !strings.EqualFold(gws[0].MAC, switchapi.DefaultVirtualMAC) {
				out = append(out, "gateway mac "+gws[0].MAC)
			}
			for _, g := range gws {
				out = append(out, fmt.Sprintf("gateway add %s %s", g.SVI, g.Address.String()))
			}
		}
	}

	return strings.Join(out, "\n") + "\n", nil
}

func configLines(s string) []string {
	var lines []string
	for _, raw := range strings.Split(s, "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		lines = append(lines, strings.Join(strings.Fields(line), " "))
	}
	return lines
}

// diffConfigs compares saved vs running network.conf (ignoring comments and
// blank lines) and returns a readable diff, or "" if identical.
func diffConfigs(saved, running string) string {
	sLines := configLines(saved)
	rLines := configLines(running)

	sSet := map[string]bool{}
	rSet := map[string]bool{}
	for _, l := range sLines {
		sSet[l] = true
	}
	for _, l := range rLines {
		rSet[l] = true
	}

	var out []string
	for _, l := range sLines {
		if !rSet[l] {
			out = append(out, "- "+l)
		}
	}
	for _, l := range rLines {
		if !sSet[l] {
			out = append(out, "+ "+l)
		}
	}
	if len(out) == 0 {
		return ""
	}
	return strings.Join(out, "\n") + "\n"
}

func runningNetConf() (string, error) {
	c, err := nosdclient.Dial(os.Getenv("NOSD_SOCKET"))
	if err != nil {
		return "", err
	}
	defer c.Close()
	ifaces, routes := collectLinuxNet()
	return renderRunningConfig(c, ifaces, routes)
}

func configRunningCmd() error {
	rendered, err := runningNetConf()
	if err != nil {
		return err
	}
	fmt.Print(rendered)
	return nil
}

func configDiffCmd() error {
	rendered, err := runningNetConf()
	if err != nil {
		return err
	}
	path := savedNetworkConfPath()
	savedBytes, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	diff := diffConfigs(string(savedBytes), rendered)
	if diff == "" {
		fmt.Printf("no differences between %s and running configuration\n", path)
		return nil
	}
	fmt.Printf("--- %s (saved)\n+++ running\n%s", path, diff)
	return nil
}

func configSaveCmd() error {
	rendered, err := runningNetConf()
	if err != nil {
		return err
	}
	path := savedNetworkConfPath()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if prev, err := os.ReadFile(path); err == nil {
		_ = os.WriteFile(path+".bak", prev, 0o644)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(rendered), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	fmt.Printf("saved running configuration to %s (%d directive(s))\n", path, len(configLines(rendered)))
	return nil
}
